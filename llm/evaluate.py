"""Score each model's eval outputs with AuditKIT, using the Sutra interpreter as the metric.

Answers were generated by SGLang on Kaggle (outputs_<model>.jsonl); AuditKIT scores them as precomputed
outputs (no model call) and ak.compare reports each tuned model against the base.

usage: python evaluate.py runs/latest/train_eval
"""
import hashlib
import json
import random
import sys
from pathlib import Path

import auditkit as ak
from auditkit.metric import Metric

import prompts
import verify


class SutraPass(Metric):
    """1.0 when the program in the answer passes every test of its task in the Sutra interpreter."""
    name = "sutra_pass"
    direction = ak.Direction.MAXIMIZE

    def identity(self):
        # The score depends on files outside AuditKIT's view: hash them so a changed test or verifier is never cached.
        files = [verify.HERE / "data" / f"tasks_{s}.jsonl" for s in ("train", "eval")] + [verify.CLI, Path(prompts.__file__)]
        return {"name": self.name, "inputs": {f.name: hashlib.sha256(f.read_bytes()).hexdigest() for f in files}}

    def score(self, sample, output, context=None):
        task = verify.TASKS[sample.metadata["task_id"]]
        res = verify.check([{"id": sample.id, "program": prompts.extract_program(output), "tests": task["tests"]}])[0]
        return ak.Score(name=self.name, value=1.0 if res.get("ok") else 0.0)


def samples(path):
    out = []
    for row in map(json.loads, open(path)):
        task = verify.TASKS[row["meta"]["task_id"]]
        for k, text in enumerate(row["outputs"]):
            out.append(ak.Sample(input=prompts.user_prompt(task), id=f"{row['id']}#{k}", actual_output=text,
                                 metadata={"task_id": task["id"]}))
    return out


def per_task(result):
    tasks = {}
    for p in result.predictions:
        tasks.setdefault(p.sample_id.split(":", 1)[1].rsplit("#", 1)[0], []).append(p.score)
    return {t: sum(s) / len(s) for t, s in tasks.items()}


def task_bootstrap(a, b, n=10000, seed=16):
    """95% interval of mean(b) - mean(a), resampling tasks (samples of one task are not independent)."""
    rng = random.Random(seed)
    tasks = sorted(a)
    diffs = sorted(sum(b[t] - a[t] for t in pick) / len(pick)
                   for pick in ([rng.choice(tasks) for _ in tasks] for _ in range(n)))
    return diffs[int(0.025 * n)], diffs[int(0.975 * n)]


def main(run_dir):
    run_dir = Path(run_dir)
    results = {}
    for f in sorted(run_dir.glob("outputs_*.jsonl")):
        name = f.stem.removeprefix("outputs_")
        results[name] = ak.evaluate(samples(f), "precomputed", [SutraPass()])
        print(f"{name}: {results[name].summary()}")
    base = next((n for n in results if n not in ("raw", "curated")), None)
    for a, b in ((base, "raw"), (base, "curated"), ("raw", "curated")):
        if a in results and b in results:
            lo, hi = task_bootstrap(per_task(results[a]), per_task(results[b]))
            print(f"\n{b} vs {a}: task-clustered 95% CI of the difference [{lo:+.3f}, {hi:+.3f}]\n"
                  f"{ak.compare(results[a], results[b]).summary()}")


if __name__ == "__main__":
    main(sys.argv[1])
